/*



=====================================================
              GETTERS & SETTERS
=====================================================

Simple Language:

Private variable ne direct bahar thi touch nathi kari sakta.

Etle vachche 2 gate banaviye:

Getter  = Data bahar kadhe
Setter  = Data andar mokle

-----------------------------------------------------

Getter:

Kaam:
Private value ne read karva mate.

Yaad rakh:

Getter = Get = Levu

Example:

name andar che
Getter thi name joi sakiye

-----------------------------------------------------

Setter:

Kaam:
Private value ne update karva mate.

Yaad rakh:

Setter = Set = Mukvu

Example:

name ne navi value apvi hoy
to Setter vapray

-----------------------------------------------------

Real Life Example:

ATM Machine

Balance = Private

Tame direct balance touch nathi kari sakta.

checkBalance()  -> Getter

depositMoney()  -> Setter

-----------------------------------------------------

Why Use Getter Setter?

1. Data Safe Rahe

Negative age
Negative salary
Wrong values

check kari sakay.

2. Control Male

Read allow
Write allow

Banne alag kari sakay.

3. Encapsulation Follow Thay

Data andar hidden rahe.

=====================================================

Shortcut Memory:

Getter = Read
Setter = Write

Getter = Get Value
Setter = Set Value

=====================================================


*/



